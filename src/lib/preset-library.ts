export function getPresetById(id: string): PresetLibraryEntry | undefined {
  return PRESET_LIBRARY.find((preset) => preset.id === id || preset.slug === id);
}

export function presetsByVibe(vibe: PresetVibe): PresetLibraryEntry[] {
  return PRESET_LIBRARY.filter((preset) => preset.vibe_tags.includes(vibe));
}

export function presetsByGender(gender: PresetLibraryEntry['gender']): PresetLibraryEntry[] {
  return PRESET_LIBRARY.filter((preset) => preset.gender === gender);
}

